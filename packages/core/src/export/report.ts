import type { Architecture } from "../schema";
import { computeArchitecture } from "../engine/compute";
import { getBlock } from "../blocks/registry";
import { diffById } from "../diff";
import { formatCount } from "../describe";
import { exportYaml } from "../compiler/export";
import { STUBS, parseModelEdits } from "./stubs";

export interface ChangeNote {
  /** Why this was changed (from the Lab or an AI patch). */
  rationale?: string;
  tradeoff?: string;
}

/** Markdown change report: every modification with its explanation, plus totals and next steps. */
export function changeReport(original: Architecture, edited: Architecture, notes: Record<string, ChangeNote> = {}, goal?: string): string {
  const ca = computeArchitecture(original), cb = computeArchitecture(edited);
  const d = diffById(original, edited, ca, cb).filter((x) => x.kind !== "same");
  const pct = (a: number, b: number) => `${b >= a ? "+" : ""}${(((b - a) / a) * 100).toFixed(1)}%`;
  const lines = [
    `# Change report — ${edited.version} ${edited.task} (${edited.config.scale ?? "custom"})`,
    "",
    goal ? `**Goal:** ${goal}\n` : "",
    "| | Original | Modified | Change |",
    "|---|---|---|---|",
    `| Parameters | ${formatCount(ca.totals.params)} | ${formatCount(cb.totals.params)} | ${pct(ca.totals.params, cb.totals.params)} |`,
    `| GFLOPs (at ${edited.inputSize}) | ${ca.totals.gflops.toFixed(1)} | ${cb.totals.gflops.toFixed(1)} | ${pct(ca.totals.gflops, cb.totals.gflops)} |`,
    `| Layers | ${ca.totals.layers} | ${cb.totals.layers} | ${cb.totals.layers - ca.totals.layers} |`,
    "",
    "Numbers are computed from the architecture; speed and accuracy are not measured here. Treat every change as a hypothesis and test it with an ablation (one change at a time).",
    "",
    "## Changes",
    "",
  ];
  if (!d.length) lines.push("_No structural changes._");
  for (const x of d) {
    const n = x.b ?? x.a!;
    const idx = x.b ? cb.nodes[x.b.id]?.index : ca.nodes[x.a!.id]?.index;
    const title = `${x.kind === "added" ? "Added" : x.kind === "removed" ? "Removed" : "Changed"}: layer ${idx} ${getBlock(n.module)?.displayName ?? n.module}`;
    const note = notes[n.modification?.opId ?? ""] ?? notes[n.id];
    lines.push(`### ${title}`, "");
    if (n.modification?.summary) lines.push(`- What: ${n.modification.summary}`);
    if (x.changes.length) lines.push(`- Details: ${x.changes.join("; ")}`);
    if (note?.rationale) lines.push(`- Why: ${note.rationale}`);
    if (note?.tradeoff) lines.push(`- Trade-off: ${note.tradeoff}`);
    lines.push("");
  }
  const extras = [...new Set(edited.nodes.map((n) => getBlock(n.module)).filter((b) => b?.extra).map((b) => b!.id))];
  lines.push("## Using this in Ultralytics", "");
  lines.push("- Pretrained weights only partly transfer after structural edits: layers whose position or shape changed start from scratch. Expect to train longer.");
  if (extras.length) {
    lines.push(`- Custom blocks used: ${extras.join(", ")}. Add the classes from \`custom_blocks.py\` and the \`parse_model\` edits below.`);
    lines.push("", "```python", parseModelEdits(extras), "```");
    if (extras.includes("CBAM")) lines.push("", "CBAM already exists in `ultralytics.nn.modules`; it only needs the parse_model edit.");
  }
  lines.push("", "## YAML", "", "```yaml", exportYaml(edited).trimEnd(), "```", "");
  return lines.filter((l, i, a) => !(l === "" && a[i - 1] === "")).join("\n");
}

/** `custom_blocks.py`: classes for Lab extras used in the model (valid nn.Module code). */
export function customBlocksPython(arch: Architecture): string {
  const extras = [...new Set(arch.nodes.map((n) => getBlock(n.module)).filter((b) => b?.extra).map((b) => b!.id))];
  const body = extras.map((id) => STUBS[id]).filter((s) => s && s.code).map((s) => s!.code);
  return [
    '"""Custom blocks generated by YOLO Atlas. Import these where Ultralytics builds models',
    "(e.g. in ultralytics/nn/tasks.py) and apply the parse_model edits below.",
    "",
    parseModelEdits(extras).split("\n").map((l) => l).join("\n"),
    '"""',
    "",
    "import torch",
    "import torch.nn as nn",
    "",
    "",
    body.length ? body.join("\n\n\n") : "# This model uses no custom blocks.",
    "",
  ].join("\n");
}

/** Minimal training script for the exported YAML. */
export function trainingScript(arch: Architecture, yamlFile = "model.yaml"): string {
  const weights = { v8: "yolov8", "11": "yolo11", "26": "yolo26", "12": "yolo12", v10: "yolov10", v9: "yolov9" }[arch.version];
  const scale = arch.config.scale && arch.config.scale !== "custom" ? arch.config.scale : "n";
  const task = { detect: "", segment: "-seg", pose: "-pose", classify: "-cls", obb: "-obb" }[arch.task];
  return `"""Train the modified model. Generated by YOLO Atlas.

1. Put your dataset YAML (paths + class names) next to this file, e.g. data.yaml with nc: ${arch.config.nc}.
2. If the model uses custom blocks, register them first (see custom_blocks.py).
"""
from ultralytics import YOLO

model = YOLO("${yamlFile}")${weights ? `
# Optional: start from official weights. Only layers with matching names and shapes are loaded;
# changed or added layers start from scratch.
model.load("${weights}${scale}${task}.pt")` : ""}

model.train(
    data="data.yaml",
    imgsz=${arch.inputSize},
    epochs=100,
    batch=16,
)
metrics = model.val()
print(metrics)
`;
}
